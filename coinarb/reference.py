# Имперское золото по номиналу В РУБЛЯХ (1700-1911): 5, 7.5, 10, 15, 20 рублей
IMPERIAL_GOLD = {"5": 4.30, "7.5": 6.45, "10": 8.60, "15": 12.90, "20": 17.20}

# Веса, по которым 25 рублей однозначно определяется даже в «спорные» годы.
_W25 = [(150.0, 160.0, "Ag"), (8.0, 11.0, "Ni")]


def imperial_gold(year: int | None, denom: str | None) -> bool:
    """Имперское золото определяется по номиналу В РУБЛЯХ.

    Критично: '15 копеек' не должно превращаться в '15 рублей' — иначе серебряные
    копейки уедут в золото и вся оценка станет ложной.
    """
    if not year or not denom: return False
    if "коп" in denom.lower(): return False
    d = re.sub(r"[^\d.]", "", denom)
    return d in IMPERIAL_GOLD and 1700 <= year <= 1911


def infer(title: str, year: int | None, denom: str | None,
          weight_g: float | None = None) -> tuple[str | None, float | None]:
    """Возвращает (metal, weight_g). None означает «достоверно определить нельзя».

    Правила матчатся и по заголовку, и по каноническому номиналу: «Гривенник 1780»
    в заголовке не содержит «10 коп», но normalize уже привёл номинал к «10 коп».
    """
    low = (" ".join(title.split()) + " " + (denom or "")).lower()

    if imperial_gold(year, denom):
        return "Au", IMPERIAL_GOLD[re.sub(r"[^\d.]", "", denom or "")]

    # 25 рублей: вес в заголовке решает спор Ag/Ni без оглядки на год.
    d25 = denom and re.sub(r"[^\d.]", "", denom) == "25" and "руб" in (denom or "")
    if d25 and weight_g:
        for lo, hi, metal in _W25:
            if lo <= weight_g <= hi:
                return metal, weight_g

    for pat, y_from, y_to, metal, weight, _c in RULES:
        if not re.search(pat, low):
            continue
        if year is None or not (y_from <= year <= y_to):
            continue
        return metal, weight
    return None, None


def describe() -> str:
    return "\n".join(f"{p!r:32} {a}-{b}: {m} {w or ''} — {c}" for p, a, b, m, w, c in RULES)
