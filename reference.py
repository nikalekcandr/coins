"""Справочник: восстановление металла и веса по типу монеты, когда продавец их не указал.

Зачем: металл указан меньше чем в половине заголовков, а без него нельзя ни
сопоставлять лоты, ни проверять вес. Ошибка здесь дороже, чем отсутствие данных,
поэтому каждое правило ограничено диапазоном лет и точным номиналом.
"""
from __future__ import annotations
import re

# (regex, year_from, year_to, metal, weight_g, comment)
# Порядок важен: проверяются сверху вниз, первое совпадение выигрывает.
RULES: list[tuple[str, int, int, str, float | None, str]] = [
    # --- СССР / РФ: драгоценные серии ---
    (r"\b150\s*руб", 1977, 1995, "Pt", 15.55, "Олимпиада-80 / платина СССР"),
    (r"\b100\s*руб", 1977, 1996, "Au", 17.45, "золотые 100 рублей СССР"),
    (r"\b50\s*руб", 1988, 1996, "Au", 8.75, "золотые 50 рублей СССР"),
    (r"\b25\s*руб", 1988, 1991, "Pd", 31.10, "палладиевые 25 рублей (Русский балет)"),
    (r"\b25\s*руб", 1992, 2100, "Ag", 155.50, "серебряные 25 рублей РФ"),
    (r"\b10\s*руб", 1977, 1996, "Au", 2.00, "золотые 10 рублей (Червонец/балет)"),
    (r"\b5\s*руб", 1989, 1991, "Pd", 7.87, "палладиевые 5 рублей (Русский балет)"),
    (r"\b3\s*руб", 1987, 1995, "Ag", 33.93, "серебряные памятные 3 рубля"),
    (r"\b3\s*руб", 1992, 2100, "Ag", 33.93, "серебряные 3 рубля РФ"),
    (r"\b2\s*руб", 1995, 2100, "Ag", 15.55, "серебряные 2 рубля РФ"),
    # --- СССР / РФ: недрагоценная основа ---
    (r"\b(150|100|50|25|10|5|3|2)\s*руб", 1992, 2100, "Ni", None, "биметалл/мельхиор РФ"),
    (r"\b(5|3|2|1)\s*рубл", 1961, 1991, "Ni", None, "медно-никель СССР"),
    (r"\b1\s*рубл", 1997, 2100, "Ni", None, "рубль РФ"),
    (r"\b50\s*коп", 1961, 1991, "Ni", None, "50 копеек СССР"),
    (r"\b50\s*коп", 1997, 2100, "Ni", None, "50 копеек РФ"),
    # --- серебро разменное ---
    (r"\b(10|15|20)\s*коп", 1867, 1917, "Ag", None, "серебряные разменные копейки империи"),
    (r"\b(10|15|20)\s*коп", 1921, 1931, "Ag", None, "серебро СССР"),
    (r"\b(10|15|20)\s*коп", 1931, 1961, "Ni", None, "медно-никель СССР"),
    # --- империя ---
    (r"(полтина|полтинник)", 1700, 1917, "Ag", None, "полтина серебро"),
    (r"\bрубл", 1700, 1917, "Ag", None, "рубль серебро"),
    (r"копе", 1700, 1866, "Cu", None, "копейки медь (до введения серебряных разменных)"),
    (r"\b(1|2|3|5|полушка|деньга)\b.*коп|копе", 1700, 1917, "Cu", None, "прочая медь империи"),
    (r"копе", 1924, 1961, "Cu", None, "советская медь до реформы"),
]

# Имперское золото по номиналу (1700-1911): 5, 10, 15, 7.5, 20 рублей
IMPERIAL_GOLD = {"5": 4.30, "7.5": 6.45, "10": 8.60, "15": 12.90, "20": 17.20}

def imperial_gold(year: int | None, denom: str | None) -> bool:
    """Имперское золото определяется по номиналу В РУБЛЯХ.

    Критично: '15 копеек' не должно превращаться в '15 рублей' — иначе серебряные
    копейки уедут в золото и вся оценка станет ложной.
    """
    if not year or not denom: return False
    if "коп" in denom.lower(): return False
    d = re.sub(r"[^\d.]", "", denom)
    return d in IMPERIAL_GOLD and 1700 <= year <= 1911

def infer(title: str, year: int | None, denom: str | None) -> tuple[str | None, float | None]:
    """Возвращает (metal, weight_g). None означает «достоверно определить нельзя»."""
    low = " ".join(title.split()).lower()

    if imperial_gold(year, denom):
        return "Au", IMPERIAL_GOLD[re.sub(r"[^\d.]", "", denom or "")]

    for pat, y_from, y_to, metal, weight, _c in RULES:
        if not re.search(pat, low):
            continue
        if year is None or not (y_from <= year <= y_to):
            continue
        return metal, weight
    return None, None

def describe() -> str:
    return "\n".join(f"{p!r:32} {a}-{b}: {m} {w or ''} — {c}" for p, a, b, m, w, c in RULES)
